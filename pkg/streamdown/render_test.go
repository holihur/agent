package streamdown

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// renderFixture renders a testdata file with the given width and plaintext
// mode and returns the raw bytes written to the output writer.
func renderFixture(t *testing.T, name string, width int, plaintext bool) []byte {
	t.Helper()
	cfg := DefaultConfig()
	cfg.Width = width
	cfg.Plaintext = plaintext
	var buf bytes.Buffer
	r, err := New(&buf, cfg)
	if err != nil {
		t.Fatalf("New: %v", err)
	}
	data, err := os.ReadFile(filepath.Join("testdata", name))
	if err != nil {
		t.Fatalf("read fixture: %v", err)
	}
	if err := r.RenderString(string(data)); err != nil {
		t.Fatalf("RenderString: %v", err)
	}
	return buf.Bytes()
}

// TestGoldenANSIGo compares rendered output byte-for-byte against goldens
// generated by the reference Python implementation (pkg/streamdown/tools).
// The goldens cover headings, inline styles, lists, tables, blockquotes,
// links, rules and setext headings — everything except code-block syntax
// colours, which use a different (but equivalent) highlighter in Go.
func TestGoldenANSI(t *testing.T) {
	cases := []struct {
		fixture string
		golden  string
		width   int
	}{
		{"basic.md", "basic.ansi.golden", 80},
		{"cjk.md", "cjk.ansi.golden", 60},
	}
	for _, tc := range cases {
		t.Run(tc.fixture, func(t *testing.T) {
			got := renderFixture(t, tc.fixture, tc.width, false)
			want, err := os.ReadFile(filepath.Join("testdata", tc.golden))
			if err != nil {
				t.Fatalf("read golden: %v", err)
			}
			if !bytes.Equal(got, want) {
				t.Errorf("ANSI output mismatch\n--- got ---\n%q\n--- want ---\n%q", got, want)
			}
		})
	}
}

