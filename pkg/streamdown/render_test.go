// TestRenderIsStateless verifies that rendering multiple documents with one
// renderer produces the same output as a fresh renderer each time (no state
// leaks between documents).
func TestRenderIsStateless(t *testing.T) {
	fixtures := []string{"basic.md", "cjk.md", "full.md"}
	for _, name := range fixtures {
		t.Run(name, func(t *testing.T) {
			var first, second bytes.Buffer
			for _, buf := range []*bytes.Buffer{&first, &second} {
				cfg := DefaultConfig()
				cfg.Width = 80
				r, err := New(buf, cfg)
				if err != nil {
					t.Fatal(err)
				}
				data, err := os.ReadFile(filepath.Join("testdata", name))
				if err != nil {
					t.Fatal(err)
				}
				if err := r.RenderString(string(data)); err != nil {
					t.Fatal(err)
				}
			}
			if !bytes.Equal(first.Bytes(), second.Bytes()) {
				t.Errorf("state leaked between renders")
			}
		})
	}
}

// TestRenderString trivially wraps Render and must behave identically.
func TestRenderString(t *testing.T) {
	cfg := DefaultConfig()
	cfg.Width = 60
	cfg.Plaintext = true
	var a, b bytes.Buffer
	ra, _ := New(&a, cfg)
	rb, _ := New(&b, cfg)
	src := "# 标题\n\n正文 **加粗** 内容。\n"
	if err := ra.RenderString(src); err != nil {
		t.Fatal(err)
	}
	if err := rb.Render(strings.NewReader(src)); err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(a.Bytes(), b.Bytes()) {
		t.Errorf("RenderString != Render")
	}
}
